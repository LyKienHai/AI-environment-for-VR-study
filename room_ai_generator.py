# ── Ollama provider ───────────────────────────────────────────────────────────
class OllamaProvider:
    NAME     = "Ollama (local)"
    BASE_URL = "http://localhost:11434"
    # Preferred code models in order — first available one is used
    PREFERRED = [
        "qwen2.5-coder:7b",
        "qwen2.5-coder:3b",
        "deepseek-coder:6.7b",
        "codellama:7b",
        "codellama:13b",
        "llama3.1:8b",
        "llama3:8b",
        "mistral:7b",
    ]

    def __init__(self):
        self.model = self._detect_model()

    def _detect_model(self) -> Optional[str]:
        try:
            resp = requests.get(f"{self.BASE_URL}/api/tags", timeout=5)
            if resp.status_code != 200:
                return None
            available = [m["name"] for m in resp.json().get("models", [])]
            print(f"[RoomAI] Ollama models available: {available}")
            for pref in self.PREFERRED:
                if pref in available:
                    print(f"[RoomAI] Ollama selected: {pref}")
                    return pref
            # Fall back to first available
            return available[0] if available else None
        except Exception:
            return None

    def generate(self, user_request: str) -> Optional[str]:
        if not self.model:
            print("[RoomAI] Ollama ✗  not running or no models found")
            return None
        try:
            t0   = time.time()
            prompt = f"{SYSTEM_PROMPT}\n\nUser request: {user_request}\n\nOutput ONLY Prim() lines (minimum 6, use f suffix on all numbers):"
            resp = requests.post(
                f"{self.BASE_URL}/api/generate",
                json={"model": self.model, "prompt": prompt,
                      "stream": False, "options": {"temperature": 0.20, "num_predict": 2500}},
                timeout=120,
            )
            elapsed = time.time() - t0
            if resp.status_code == 200:
                text = resp.json().get("response", "").strip()
                print(f"[RoomAI] Ollama ✓  model={self.model} ({elapsed:.1f}s)")
                return text
            print(f"[RoomAI] Ollama ✗  HTTP {resp.status_code}")
        except Exception as e:
            print(f"[RoomAI] Ollama ✗  {e}")
        return None


# ── Code extractor ────────────────────────────────────────────────────────────
def _add_float_suffixes(line: str) -> str:
    """Ensure all decimal literals have 'f' suffix (e.g. 0.5 → 0.5f).
    The negative lookahead (?![f\\d]) prevents matching a partial number —
    e.g. 2.16f would previously match 2.1 (since 2.16 fails (?!f)),
    producing 2.1f6f. Now we also reject if the next char is a digit."""
    return re.sub(r'(\d+\.\d+)(?![f\d])', r'\1f', line)

def extract_prim_lines(raw: str) -> str:
    """Keep only valid Prim(...); lines, strip everything else."""
    lines = []
    # Strip markdown code blocks
    raw = re.sub(r"```[a-z]*", "", raw)
    for line in raw.splitlines():
        stripped = line.strip()
        if stripped.startswith("Prim(") and stripped.endswith(");"):
            stripped = _add_float_suffixes(stripped)
            lines.append("        " + stripped)
    return "\n".join(lines)


# ── Main generator class ──────────────────────────────────────────────────────
class RoomAIGenerator:
    def __init__(self, groq_key: str = "", gemini_key: str = ""):
        self.providers = []
        if groq_key:
            self.providers.append(GroqProvider(groq_key))
        if gemini_key:
            self.providers.append(GeminiProvider(gemini_key))
        self.ollama = OllamaProvider()
        self.providers.append(self.ollama)   # always last fallback

    def generate(self, user_request: str) -> tuple[bool, str, str, str]:
        """
        Returns (success, status_message, generated_cs_code, output_filename)
        Each generation is saved as its own named .cs file so you can delete
        individual objects without affecting the rest of the room.
        """
        raw  = None
        used = "none"

        for provider in self.providers:
            print(f"[RoomAI] Trying {provider.NAME}…")
            raw = provider.generate(user_request)
            if raw:
                used = provider.NAME
                break

        if not raw:
            return False, "❌ All providers failed — check connections.", "", ""

        # ── Class name & filename derived from the request ─────────────────────
        classname   = _make_classname(user_request)
        output_file = f"{classname}.cs"

        body = extract_prim_lines(raw)
        if not body.strip():
            body = (f'        // Could not parse output — raw:\n'
                    f'        // {raw[:200]}\n'
                    f'        Prim(PrimitiveType.Cube, "Fallback", '
                    f'new Vector3(0,-2f,0), new Vector3(0.5f,0.5f,0.5f), new Color(1,0,0));')

        cs = CS_TEMPLATE.format(
            classname=classname,
            request=user_request.replace("{", "{{").replace("}", "}}"),
            provider=used,
            timestamp=time.strftime("%Y-%m-%d %H:%M:%S"),
            body=body,
        )

        # ── Save ──────────────────────────────────────────────────────────────
        # 1. Workspace copy (always) — named after the object
        ws_path = WORKSPACE_DIR / output_file
        ws_path.write_text(cs, encoding="utf-8")

        # 2. Unity Assets folder (auto-triggers recompile if Unity is open)
        unity_ok = False
        if UNITY_ASSETS.exists():
            try:
                (UNITY_ASSETS / output_file).write_text(cs, encoding="utf-8")
                unity_ok = True
            except Exception as e:
                print(f"[RoomAI] Unity write failed: {e}")

        dest = "Unity Assets (auto-recompiling ✨)" if unity_ok else "workspace (run copy_to_unity.bat)"
        status = (f"✅ Generated via **{used}**\n"
                  f"📄 File: `{output_file}` → {dest}\n"
                  f"🗑️ To delete: remove `{output_file}` from Unity Assets and recompile.")
        return True, status, cs, output_file


