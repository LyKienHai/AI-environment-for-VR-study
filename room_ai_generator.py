# ── Filler words stripped when building the class / file name ─────────────────
_FILLER = {
    'a','an','the','add','put','place','create','make','generate','some',
    'near','in','on','at','by','to','with','of','and','or','for',
    'there','is','are','please','would','like','want','i','me',
}

def _make_classname(request: str) -> str:
    """Convert a freeform request to a valid C# class name used as filename.
    Examples:
      'chair corner'               → 'Chair_Corner'
      'grand piano near window'    → 'GrandPiano_Window'
      'coat rack back wall hooks'  → 'CoatRack_BackWall'
    """
    words = re.findall(r'[a-zA-Z]+', request.lower())
    words = [w for w in words if w not in _FILLER]
    if not words:
        return 'RoomAIObject'
    caps = [w.capitalize() for w in words[:5]]
    obj_part = ''.join(caps[:min(2, len(caps))])
    loc_part = ''.join(caps[2:4])
    name = f'{obj_part}_{loc_part}' if loc_part else obj_part
    if name[0].isdigit():
        name = 'Obj_' + name
    return name

